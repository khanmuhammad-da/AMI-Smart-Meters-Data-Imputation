def validate_prediction_dataframe(
    dataframe: pd.DataFrame,
    gap_length: int
) -> str:
    """
    Validate one saved prediction dataframe.
    """

    subsection(
        f"GAP {gap_length} INPUT VALIDATION"
    )

    # -------------------------------------------------------------------------
    # Required columns.
    # -------------------------------------------------------------------------

    required_columns = [
        "ground_truth",
        "split",
    ]

    missing_columns = [
        column
        for column in required_columns
        if column not in dataframe.columns
    ]

    if missing_columns:

        fail(
            f"Gap {gap_length}: missing required columns:\n"
            f"{missing_columns}"
        )

    info(
        "Required columns       : PASSED"
    )

    # -------------------------------------------------------------------------
    # Prediction column.
    # -------------------------------------------------------------------------

    prediction_column = (
        find_prediction_column(
            dataframe
        )
    )

    info(
        f"Prediction column     : {prediction_column}"
    )

    # -------------------------------------------------------------------------
    # Ground truth.
    # -------------------------------------------------------------------------

    if dataframe[
        "ground_truth"
    ].isna().any():

        fail(
            f"Gap {gap_length}: "
            "ground_truth contains NaN."
        )

    if np.isinf(
        dataframe[
            "ground_truth"
        ].to_numpy(
            dtype=float
        )
    ).any():

        fail(
            f"Gap {gap_length}: "
            "ground_truth contains Inf."
        )

    info(
        "Ground truth           : PASSED"
    )

    # -------------------------------------------------------------------------
    # Predictions.
    # -------------------------------------------------------------------------

    if dataframe[
        prediction_column
    ].isna().any():

        fail(
            f"Gap {gap_length}: "
            "prediction contains NaN."
        )

    if np.isinf(
        dataframe[
            prediction_column
        ].to_numpy(
            dtype=float
        )
    ).any():

        fail(
            f"Gap {gap_length}: "
            "prediction contains Inf."
        )

    info(
        "Predictions            : PASSED"
    )

    # -------------------------------------------------------------------------
    # Split labels.
    # -------------------------------------------------------------------------

    valid_splits = {
        "train",
        "validation",
        "test",
    }

    actual_splits = set(
        dataframe[
            "split"
        ].astype(str).unique()
    )

    invalid_splits = (
        actual_splits
        -
        valid_splits
    )

    if invalid_splits:

        fail(
            f"Gap {gap_length}: "
            f"invalid split labels: {invalid_splits}"
        )

    info(
        "Split labels           : PASSED"
    )

    # -------------------------------------------------------------------------
    # Timestamp.
    # -------------------------------------------------------------------------

    if "Time" in dataframe.columns:

        parsed_time = pd.to_datetime(
            dataframe["Time"],
            errors="coerce"
        )

        if parsed_time.isna().any():

            fail(
                f"Gap {gap_length}: "
                "invalid timestamps found."
            )

        info(
            "Timestamp              : PASSED"
        )

    # -------------------------------------------------------------------------
    # Target index.
    # -------------------------------------------------------------------------

    if "target_index" in dataframe.columns:

        if dataframe[
            "target_index"
        ].isna().any():

            fail(
                f"Gap {gap_length}: "
                "target_index contains NaN."
            )

        info(
            "Target index            : PASSED"
        )

    # -------------------------------------------------------------------------
    # Event ID.
    # -------------------------------------------------------------------------

    if "event_id" in dataframe.columns:

        if dataframe[
            "event_id"
        ].isna().any():

            fail(
                f"Gap {gap_length}: "
                "event_id contains NaN."
            )

        info(
            "Event IDs              : PASSED"
        )

    # -------------------------------------------------------------------------
    # Gap length.
    # -------------------------------------------------------------------------

    if "gap_length" in dataframe.columns:

        actual_gap_lengths = set(
            dataframe[
                "gap_length"
            ].astype(int).unique()
        )

        if actual_gap_lengths != {
            gap_length
        }:

            fail(
                f"Gap {gap_length}: "
                f"unexpected gap_length values: "
                f"{actual_gap_lengths}"
            )

        info(
            "Gap length             : PASSED"
        )

    # -------------------------------------------------------------------------
    # Dataset not empty.
    # -------------------------------------------------------------------------

    if len(dataframe) == 0:

        fail(
            f"Gap {gap_length}: "
            "prediction dataframe is empty."
        )

    info(
        f"Rows                   : {len(dataframe):,}"
    )

    info(
        "Prediction dataframe   : PASSED"
    )

    return prediction_column


# =============================================================================
# METRIC CALCULATION
# =============================================================================

def calculate_metrics(
    y_true: np.ndarray,
    y_pred: np.ndarray
) -> Dict[str, float]:
    """
    Calculate regression metrics.

    Metrics
    -------
    MAE
    RMSE
    R2
    MAPE
    MAE as percentage of mean actual
    Mean bias
    Maximum absolute error
    Median absolute error
    """

    y_true = np.asarray(
        y_true,
        dtype=float
    )

    y_pred = np.asarray(
        y_pred,
        dtype=float
    )

    if len(y_true) == 0:

        fail(
            "Cannot calculate metrics "
            "for an empty dataset."
        )

    # -------------------------------------------------------------------------
    # Error.
    # -------------------------------------------------------------------------

    error = (
        y_pred
        -
        y_true
    )

    absolute_error = np.abs(
        error
    )

    # -------------------------------------------------------------------------
    # MAE.
    # -------------------------------------------------------------------------

    mae = mean_absolute_error(
        y_true,
        y_pred
    )

    # -------------------------------------------------------------------------
    # RMSE.
    # -------------------------------------------------------------------------

    rmse = math.sqrt(
        mean_squared_error(
            y_true,
            y_pred
        )
    )

    # -------------------------------------------------------------------------
    # R2.
    # -------------------------------------------------------------------------

    if len(y_true) >= 2:

        r2 = r2_score(
            y_true,
            y_pred
        )

    else:

        r2 = np.nan

    # -------------------------------------------------------------------------
    # MAPE.
    #
    # Zero actual values are excluded because percentage error is undefined.
    # -------------------------------------------------------------------------

    non_zero = (
        y_true != 0
    )

    if non_zero.any():

        mape = (
            np.mean(
                np.abs(
                    (
                        y_pred[non_zero]
                        -
                        y_true[non_zero]
                    )
                    /
                    y_true[non_zero]
                )
            )
            *
            100.0
        )

    else:

        mape = np.nan

    # -------------------------------------------------------------------------
    # MAE relative to mean actual.
    # -------------------------------------------------------------------------

    mean_actual_abs = np.mean(
        np.abs(y_true)
    )

    if mean_actual_abs != 0:

        mae_percent = (
            mae
            /
            mean_actual_abs
        ) * 100.0

    else:

        mae_percent = np.nan

    # -------------------------------------------------------------------------
    # Return.
    # -------------------------------------------------------------------------

    return {

        "samples":
            int(len(y_true)),

        "MAE":
            float(mae),

        "RMSE":
            float(rmse),

        "R2":
            float(r2),

        "MAPE_percent":
            float(mape),

        "MAE_percent_of_mean":
            float(mae_percent),

        "mean_actual":
            float(np.mean(y_true)),

        "mean_prediction":
            float(np.mean(y_pred)),

        "mean_error_bias":
            float(np.mean(error)),

        "max_absolute_error":
            float(np.max(absolute_error)),

        "median_absolute_error":
            float(np.median(absolute_error)),

        "min_actual":
            float(np.min(y_true)),

        "max_actual":
            float(np.max(y_true)),
    }


# =============================================================================
# SPLIT EVALUATION
# =============================================================================

def evaluate_by_split(
    dataframe: pd.DataFrame,
    prediction_column: str,
    gap_length: int
) -> pd.DataFrame:
    """
    Evaluate train, validation and test predictions.
    """

    records = []

    for split in [
        "train",
        "validation",
        "test",
    ]:

        subset = dataframe[
            dataframe[
                "split"
            ].astype(str)
            ==
            split
        ]

        if subset.empty:
            continue

        metrics = calculate_metrics(
            y_true=subset[
                "ground_truth"
            ].to_numpy(),
            y_pred=subset[
                prediction_column
            ].to_numpy(),
        )

        records.append({
            "gap_length":
                gap_length,

            "split":
                split,

            **metrics,
        })

    return pd.DataFrame(
        records
    )


# =============================================================================
# TEST POSITION EVALUATION
# =============================================================================

def evaluate_test_positions(
    dataframe: pd.DataFrame,
    prediction_column: str,
    gap_length: int
) -> pd.DataFrame:
    """
    Evaluate performance separately for each LP position
    inside the missing event.

    For a 6 LP gap:

        position 1
        position 2
        position 3
        position 4
        position 5
        position 6
    """

    if "gap_position" not in dataframe.columns:

        fail(
            f"Gap {gap_length}: "
            "gap_position column missing."
        )

    test = dataframe[
        dataframe[
            "split"
        ].astype(str)
        ==
        "test"
    ].copy()

    records = []

    positions = sorted(
        test[
            "gap_position"
        ].unique()
    )

    for position in positions:

        subset = test[
            test[
                "gap_position"
            ]
            ==
            position
        ]

        metrics = calculate_metrics(
            y_true=subset[
                "ground_truth"
            ].to_numpy(),
            y_pred=subset[
                prediction_column
            ].to_numpy(),
        )

        records.append({
            "gap_length":
                gap_length,

            "gap_position":
                int(position),

            **metrics,
        })

    return pd.DataFrame(
        records
    )


# =============================================================================
# TEST EVENT EVALUATION
# =============================================================================

def evaluate_test_events(
    dataframe: pd.DataFrame,
    prediction_column: str,
    gap_length: int
) -> pd.DataFrame:
    """
    Evaluate each independent test event.

    This is important because LP-level samples inside one
    event are not independent events.
    """

    if "event_id" not in dataframe.columns:

        fail(
            f"Gap {gap_length}: "
            "event_id column missing."
        )

    test = dataframe[
        dataframe[
            "split"
        ].astype(str)
        ==
        "test"
    ].copy()

    records = []

    event_ids = sorted(
        test[
            "event_id"
        ].unique()
    )

    for event_id in event_ids:

        subset = test[
            test[
                "event_id"
            ]
            ==
            event_id
        ]

        metrics = calculate_metrics(
            y_true=subset[
                "ground_truth"
            ].to_numpy(),
            y_pred=subset[
                prediction_column
            ].to_numpy(),
        )

        record = {

            "gap_length":
                gap_length,

            "event_id":
                int(event_id),

            **metrics,
        }

        if "Time" in subset.columns:

            record[
                "event_start"
            ] = str(
                subset[
                    "Time"
                ].min()
            )

            record[
                "event_end"
            ] = str(
                subset[
                    "Time"
                ].max()
            )

        records.append(
            record
        )

    return pd.DataFrame(
        records
    )


# =============================================================================
# PREDICTION ERROR DATAFRAME
# =============================================================================

def create_prediction_error_dataframe(
    dataframe: pd.DataFrame,
    prediction_column: str,
    gap_length: int
) -> pd.DataFrame:
    """
    Add explicit prediction error columns.
    """

    output = dataframe.copy()

    output[
        "prediction_error"
    ] = (
        output[
            prediction_column
        ]
        -
        output[
            "ground_truth"
        ]
    )

    output[
        "absolute_error"
    ] = np.abs(
        output[
            "prediction_error"
        ]
    )

    output[
        "percentage_error"
    ] = np.where(

        output[
            "ground_truth"
        ] != 0,

        (
            output[
                "absolute_error"
            ]
            /
            np.abs(
                output[
                    "ground_truth"
                ]
            )
        )
        *
        100.0,

        np.nan
    )

    output[
        "evaluation_gap_length"
    ] = gap_length

    return output


# =============================================================================
# PRINT SPLIT METRICS
# =============================================================================

def print_split_metrics(
    dataframe: pd.DataFrame
) -> None:

    if dataframe.empty:
        return

    columns = [
        "split",
        "samples",
        "MAE",
        "RMSE",
        "R2",
        "MAPE_percent",
    ]

    print(
        dataframe[
            columns
        ].to_string(
            index=False,
            float_format=lambda value:
            f"{value:.4f}"
        )
    )


