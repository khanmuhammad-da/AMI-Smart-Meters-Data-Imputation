# FIND PREDICTION COLUMN
# =============================================================================

def find_prediction_column(
    dataframe: pd.DataFrame
) -> str:
    """
    Identify the model prediction column.

    The model stage may use one of several conventional
    prediction column names. We explicitly check known names.
    """

    candidates = [
        "prediction",
        "predicted",
        "y_pred",
        "prediction_kwh",
        "predicted_kwh",
        "rf_prediction",
    ]

    for column in candidates:

        if column in dataframe.columns:

            return column

    # -------------------------------------------------------------------------
    # Fallback search.
    # -------------------------------------------------------------------------

    candidates = [
        column
        for column in dataframe.columns
        if "pred" in column.lower()
    ]

    if len(candidates) == 1:

        return candidates[0]

    fail(
        "Unable to identify prediction column.\n\n"
        "Available columns:\n"
        f"{list(dataframe.columns)}"
    )


